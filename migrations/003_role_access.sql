-- v20 isolated role/access migration. Re-runnable against archived v19 schema.
CREATE TABLE IF NOT EXISTS yhn_member_roles (
 actor_id text PRIMARY KEY,
 role text NOT NULL CHECK(role IN ('機構主管','居督')),
 enabled boolean NOT NULL DEFAULT false,
 updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS yhn_isolated_access_grants (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 actor_id text NOT NULL,
 role text NOT NULL,
 case_id uuid NOT NULL REFERENCES care_cases(id),
 permission text NOT NULL CHECK(permission IN ('read','write')),
 effective_at timestamptz NOT NULL DEFAULT now(),
 expires_at timestamptz,
 revoked_at timestamptz,
 approved_by text NOT NULL,
 reason text NOT NULL,
 grant_type text NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS yhn_isolated_access_audit (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_id text NOT NULL,
 case_id uuid,
 action text NOT NULL,
 decision text NOT NULL,
 grant_id uuid,
 happened_at timestamptz NOT NULL DEFAULT now(),
 detail jsonb NOT NULL DEFAULT '{}'::jsonb
);
CREATE TABLE IF NOT EXISTS yhn_test_visits (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 case_id uuid NOT NULL REFERENCES care_cases(id),
 owner_id text NOT NULL,
 visit_type text NOT NULL CHECK(visit_type IN ('home','phone')),
 visit_date date NOT NULL,
 note text NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 revision integer NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS yhn_test_care_plans (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 case_id uuid NOT NULL UNIQUE REFERENCES care_cases(id),
 owner_id text NOT NULL,
 content jsonb NOT NULL DEFAULT '{}'::jsonb,
 revision integer NOT NULL DEFAULT 1,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS yhn_access_grants_effective_lookup ON yhn_isolated_access_grants(actor_id,case_id,permission,effective_at,expires_at) WHERE revoked_at IS NULL;
